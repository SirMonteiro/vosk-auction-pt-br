"""Generate the C# lexicon tables from the authoritative Python lexicon.

The C# port must never re-type these tables by hand: a single transposed accent or a
dropped slang entry silently changes bid values. This script reads
``auction_demo.nlu.lexicon`` (the single source of truth, itself validated by the Python
suite) and emits ``Packages/com.auction.voice/Runtime/NLU/Lexicon.cs``.

It also emits the reference text cases consumed by the C# NUnit suite, so the two test
suites can never diverge.

Usage::

    uv run python -m tools.gen_csharp_lexicon          # write files
    uv run python -m tools.gen_csharp_lexicon --check  # fail if out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from auction_demo.config import PROJECT_ROOT
from auction_demo.nlu import lexicon as lex

CS_PATH = PROJECT_ROOT / "Packages" / "com.auction.voice" / "Runtime" / "NLU" / "Lexicon.cs"
CASES_PATH = (
    PROJECT_ROOT / "Packages" / "com.auction.voice" / "Tests" / "Editor" / "ReferenceCases.g.cs"
)
PY_CASES = PROJECT_ROOT / "tests" / "fixtures" / "text_cases.jsonl"

HEADER = """// <auto-generated>
//   Generated by tools/gen_csharp_lexicon.py from src/auction_demo/nlu/lexicon.py.
//   Do not edit by hand: change the Python lexicon and re-run
//       uv run python -m tools.gen_csharp_lexicon
//   The Python lexicon is the single source of truth for these tables.
// </auto-generated>
"""


def cs_string(value: str) -> str:
    """Escape a Python string as a C# string literal (UTF-8 source, no \\u escapes)."""
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def emit_dict_str_int(name: str, doc: str, data: dict[str, int]) -> str:
    lines = [f"        /// <summary>{doc}</summary>", f"        public static readonly IReadOnlyDictionary<string, int> {name} ="]
    lines.append("            new Dictionary<string, int>(StringComparer.Ordinal)")
    lines.append("            {")
    for key, value in data.items():
        lines.append(f"                {{ {cs_string(key)}, {value} }},")
    lines.append("            };")
    return "\n".join(lines)


def emit_dict_str_float(
    name: str, doc: str, data: dict[str, float], integer_style: bool = False
) -> str:
    lines = [f"        /// <summary>{doc}</summary>", f"        public static readonly IReadOnlyDictionary<string, float> {name} ="]
    lines.append("            new Dictionary<string, float>(StringComparer.Ordinal)")
    lines.append("            {")
    for key, value in data.items():
        rendered = str(int(value)) + "f" if integer_style and float(value).is_integer() else repr(float(value)) + "f"
        lines.append(f"                {{ {cs_string(key)}, {rendered} }},")
    lines.append("            };")
    return "\n".join(lines)


def emit_set(name: str, doc: str, data) -> str:
    lines = [f"        /// <summary>{doc}</summary>", f"        public static readonly HashSet<string> {name} ="]
    lines.append("            new HashSet<string>(StringComparer.Ordinal)")
    lines.append("            {")
    for value in sorted(data):
        lines.append(f"                {cs_string(value)},")
    lines.append("            };")
    return "\n".join(lines)


def emit_idioms() -> str:
    ordered = sorted(lex.IDIOMS.items(), key=lambda item: len(item[0]), reverse=True)
    lines = [
        "        /// <summary>",
        "        /// Every idiom phrase paired with its numeric value, <b>longest first</b>.",
        "        /// The order is part of the semantics: a longer phrase must win over a shorter",
        "        /// one that is a prefix of it (<c>dois patinhos na lagoa</c> before <c>dois patinhos</c>).",
        "        /// </summary>",
        "        public static readonly KeyValuePair<string, int>[] IdiomsLongestFirst =",
        "        {",
    ]
    for phrase, value in ordered:
        lines.append(f"            new KeyValuePair<string, int>({cs_string(phrase)}, {value}),")
    lines.append("        };")
    return "\n".join(lines)


def emit_numbers_norm() -> str:
    """``_NUMBERS_NORM``: accent-stripped form -> canonical (accented) spelling.

    Python builds this from a frozenset, so accent-only collisions (``três``/``tres``)
    resolve arbitrarily. Every colliding pair classifies identically, so the choice is
    semantically irrelevant; we prefer the accented spelling so repairs read naturally.
    """
    from auction_demo.nlu.numbers import strip_accents

    table: dict[str, str] = {}
    for word in sorted(lex.all_number_words()):
        normalized = strip_accents(word)
        current = table.get(normalized)
        if current is None or sum(1 for c in word if ord(c) > 127) > sum(
            1 for c in current if ord(c) > 127
        ):
            table[normalized] = word
    lines = [
        "        /// <summary>",
        "        /// Accent-stripped spelling -> canonical spelling, for the phonetic repair pass.",
        "        /// Mirrors <c>_NUMBERS_NORM</c> in <c>nlu/phonetics.py</c>.",
        "        /// </summary>",
        "        public static readonly IReadOnlyDictionary<string, string> NumbersByNormalizedForm =",
        "            new Dictionary<string, string>(StringComparer.Ordinal)",
        "            {",
    ]
    for key in sorted(table):
        lines.append(f"                {{ {cs_string(key)}, {cs_string(table[key])} }},")
    lines.append("            };")
    return "\n".join(lines)


def build_cs() -> str:
    parts = [
        HEADER,
        "using System;",
        "using System.Collections.Generic;",
        "",
        "namespace AuctionVoice.NLU",
        "{",
        "    /// <summary>",
        "    /// Domain lexicon for Brazilian Portuguese auction bidding. Data only: no parsing",
        "    /// logic lives here. Canonical keys are accented lower case, because Vosk silently",
        "    /// drops unaccented grammar entries.",
        "    /// </summary>",
        "    /// <remarks>",
        "    /// Slang magnitudes follow the user glossary (D-8, D-8b, D-8c):",
        "    /// <c>barão</c> = x1000, <c>pau</c> = x1000, <c>placa</c> = x100000,",
        "    /// <c>conto</c>/<c>pila</c>/<c>prata</c> = x1 (currency synonyms, not magnitudes).",
        "    /// </remarks>",
        "    public static class Lexicon",
        "    {",
        emit_dict_str_int(
            "Bases",
            "0-19, tens and hundreds, including the colloquial augmentatives used in fast "
            "auction speech (duzentão, cinquentinha, milzinho).",
            lex.BASES,
        ),
        "",
        emit_dict_str_float(
            "Multipliers", "Words that scale the preceding number.", lex.MULTIPLIERS, True
        ),
        "",
        emit_dict_str_float(
            "Magnitudes",
            "Slang units that multiply the preceding number by a fixed factor. "
            "conto/pila/prata are deliberately absent: they are currency synonyms.",
            lex.MAGNITUDES,
            True,
        ),
        "",
        emit_dict_str_float(
            "Denominations", "Real banknote fauna; each value is the note's face value.", lex.DENOMINATIONS
        ),
        "",
        emit_dict_str_int(
            "SingleDigits", "Single digits, used for the spelled-digit fast path (sete seis -> 76).",
            lex.SINGLE_DIGITS,
        ),
        "",
        emit_set(
            "CurrencyUnits",
            "Words that close the current number without scaling it.",
            lex.CURRENCY_UNITS,
        ),
        "",
        emit_set(
            "NoteDenominators",
            "Quantifiers for \"duas notas de cem\".",
            lex.NOTE_DENOMINATORS,
        ),
        "",
        emit_dict_str_int("Bingo", "Bingo / jogo do bicho nicknames.", lex.BINGO),
        "",
        emit_idioms(),
        "",
        emit_set("PassPhrases", "Phrases that mean \"I am out\".", lex.PASS_PHRASES),
        "",
        emit_set("CorrectPhrases", "Phrases that retract or amend the previous bid.", lex.CORRECT_PHRASES),
        "",
        emit_set("QueryPhrases", "Phrases that ask for information instead of bidding.", lex.QUERY_PHRASES),
        "",
        emit_set(
            "ChantPhrases",
            "Auctioneer chant. These must never be parsed as bids.",
            lex.CHANT_PHRASES,
        ),
        "",
        emit_set(
            "Fillers", "Words that carry no numeric meaning and are dropped before parsing.", lex.FILLERS
        ),
        "",
        emit_set(
            "DeltaMarkers",
            "Prefixes (or the trailing \"em cima\") that turn a number into an incremental bid.",
            lex.DELTA_MARKERS,
        ),
        "",
        emit_dict_str_float(
            "MultiplierWords",
            "Multiplier verbs and nouns. dobro -> 2, triplo -> 3, metade -> 0.5.",
            lex.MULTIPLIER_WORDS,
        ),
        "",
        emit_set(
            "StopWords",
            "Function words plus every token used by an intent phrase. Nothing in this set is "
            "ever phonetically repaired: rewriting quero -> zero or sem -> cem silently turns "
            "a pass into a bid.",
            lex.STOPWORDS,
        ),
        "",
        emit_set(
            "AllNumberWords",
            "Every token that can contribute to a numeric value. A token in this set must "
            "never be rewritten into a different word class.",
            lex.all_number_words(),
        ),
        "",
        emit_numbers_norm(),
        "    }",
        "}",
        "",
    ]
    return "\n".join(parts)


def build_cases_cs() -> str:
    cases = [
        json.loads(line)
        for line in PY_CASES.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    lines = [
        HEADER,
        "using System.Collections.Generic;",
        "",
        "namespace AuctionVoice.Tests",
        "{",
        "    /// <summary>One row of the authoritative text suite (tests/fixtures/text_cases.jsonl).</summary>",
        "    public sealed class ReferenceCase",
        "    {",
        "        public string Text;",
        "        public double Value;",
        "        public bool HasAddition;",
        "        public bool HasMultiplication;",
        "        public string ActionType;",
        "        public string BidKind;",
        "    }",
        "",
        "    /// <summary>",
        f"    /// {len(cases)} reference utterances, generated from tests/fixtures/text_cases.jsonl.",
        "    /// </summary>",
        "    public static class ReferenceCases",
        "    {",
        "        public static readonly ReferenceCase[] All =",
        "        {",
    ]
    for case in cases:
        lines.append(
            "            new ReferenceCase { "
            f"Text = {cs_string(case['text'])}, "
            f"Value = {case['value']!r}d, "
            f"HasAddition = {'true' if case['has_addition'] else 'false'}, "
            f"HasMultiplication = {'true' if case['has_multiplication'] else 'false'}, "
            f"ActionType = {cs_string(case['action_type'])}, "
            f"BidKind = {cs_string(case['bid_kind'])} }},"
        )
    lines += ["        };", "    }", "}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = parser.parse_args(argv)

    outputs = {CS_PATH: build_cs(), CASES_PATH: build_cases_cs()}
    stale: list[Path] = []

    for path, content in outputs.items():
        if args.check:
            existing = path.read_text(encoding="utf-8") if path.is_file() else ""
            if existing != content:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(PROJECT_ROOT)}")

    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(PROJECT_ROOT)}", file=sys.stderr)
        print("Run: uv run python -m tools.gen_csharp_lexicon", file=sys.stderr)
        return 1

    if args.check:
        print("generated C# tables are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
