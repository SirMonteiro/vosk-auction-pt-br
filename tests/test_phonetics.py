@pytest.mark.parametrize(
    ("corrupted", "repaired_substring"),
    [
        ("sixenta", "sessenta"),
        ("sisenta", "sessenta"),
        ("seicenta", "sessenta"),
        ("novem mil", "nove mil"),
        ("noventenove", "noventa e nove"),
        ("noventenói", "noventa e nove"),
        ("noventa em nove", "noventa e nove"),
        ("mas vinte", "mais vinte"),
        ("sem reais", "cem reais"),
        ("mew zom", "milzão"),
        ("muzinho", "milzinho"),
        ("vindes", "vinte"),
        ("vídeo", "vinte"),
        ("vite", "vinte"),
        ("cinco itinhas", "cinquentinha"),
        ("duza então", "duzentão"),
        ("quinza então", "quinhentão"),
        ("tresentão", "trezentão"),
        ("seissentos", "seiscentos"),
        ("cinquenta ca", "cinquenta mil"),
    ],
)
def test_explicit_phonetic_repairs(corrupted: str, repaired_substring: str) -> None:
    repaired, repairs = repair_phonetics(corrupted)
    assert repaired_substring in repaired
    assert len(repairs) > 0


def test_stoplist_has_zero_false_positives() -> None:
    """No word in the 200-word stoplist should be converted into a number."""
    for word in STOPLIST_200:
        repaired, repairs = repair_phonetics(word)
        # The stopword itself must remain unchanged
        assert repaired == word, f"Stopword '{word}' was incorrectly repaired to '{repaired}'"
        assert len(repairs) == 0


def test_quero_never_repairs_to_zero() -> None:
    """Explicit regression test: 'quero' must never become 'zero'."""
    res = parse("quero")
    assert res.value == 0.0
    assert res.action_type == "NONE"
    assert res.bid_kind == "UNKNOWN"
    repaired, _ = repair_phonetics("quero")
    assert "zero" not in repaired


def test_sem_lance_never_repairs_to_cem_lance() -> None:
    """Explicit regression test: 'sem lance' must remain a PASS intent, not R$ 100."""
    res = parse("sem lance")
    assert res.value == 0.0
    assert res.action_type == "PASS"
    assert res.bid_kind == "PASS"
    repaired, _ = repair_phonetics("sem lance")
    assert "cem" not in repaired
